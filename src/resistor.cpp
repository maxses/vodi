CResistor CResistor::bestMatch(const QList<CResistor>& series)
{
   CResistor r(1000000);
   for( const auto &m: series )
   {
      if( ( m < r ) && ( m > *this ) )
      {
         r=m;
      }
   }

   return(r);
}


